"""Prove that the committed migrations build the schema of the committed reference.

The script migrates one empty PostgreSQL 18 database with ``bonafides migrate``'s
code path, dumps its schema with the server's own ``pg_dump`` inside the database
container, normalises the dump and compares it with the reference byte for byte.

Normalisation removes only what is not schema, or what differs between two dumps of
the same schema:

1. pg_dump banners and ``\\restrict``/``\\unrestrict`` lines (a random key per run);
2. session ``SET`` lines and ``pg_catalog.set_config`` calls;
3. the ``--`` frame lines around each object header, and blank lines before and
   after each entry (blank lines inside an entry, such as in function bodies, stay);
4. the order of whole object entries (pg_dump breaks ties by object identifier,
   which depends on creation history); lines inside an entry keep their order.

Ledger and Alembic rows are data, so a schema-only dump never contains them; the
appended facts count every other table's fresh-install rows and record the runtime
role's database privilege, which a schema dump can't show. Ownership, grants,
revocations, constraints, defaults, triggers and function bodies are compared as
dumped.

``check`` exits 0 on equality and 1 with a unified diff otherwise. ``reference``
writes the normalised dump; ``baseline`` writes a reviewed-source SQL file that
recreates the dumped ``bonafides`` schema and its fresh-install rows.
"""

from __future__ import annotations

import argparse
import difflib
import re
import subprocess
import sys
from collections.abc import Sequence
from pathlib import Path

from sqlalchemy import Connection, create_engine, text
from sqlalchemy.engine import make_url

from bonafides.config import MigrationSettings, read_secret
from bonafides.workflows import migrate

SCHEMAS = ("bonafides", "bonafides_migrations")
LEDGER_TABLES = frozenset({"bonafides.schema_migrations", "bonafides_migrations.alembic_version"})
MIGRATOR = "bonafides_migrator"
_SESSION = re.compile(r"(SET [a-z_]+ = .*|SELECT pg_catalog\.set_config\(.*\));\Z")
_BANNER = re.compile(r"-- (PostgreSQL database dump( complete)?|Dumped (from|by) .*)\Z")
_RESTRICT = re.compile(r"\\(un)?restrict [A-Za-z0-9]+\Z")
_HEADER = re.compile(r"-- (Name|Data for Name): .*\Z")
_OWNER = re.compile(r"ALTER [A-Z ]+ \S+(\(.*\))? OWNER TO (\S+);\Z")
# pg_dump deparses BETWEEN into a parenthesised AND that PostgreSQL re-parses into a
# flatter expression tree. Restore the chain's spelling so the stored tree is equal.
RESPELLED = {
    "CHECK ((((length(rate_limit_retry_after_seconds) >= 1) AND "
    "(length(rate_limit_retry_after_seconds) <= 4096)) AND "
    "(rate_limit_retry_after_seconds ~ '^[0-9]+$'::text)))": (
        "CHECK (length(rate_limit_retry_after_seconds) BETWEEN 1 AND 4096 "
        "AND rate_limit_retry_after_seconds ~ '^[0-9]+$')"
    ),
}
REFERENCE_HEADER = """\
-- SPDX-License-Identifier: MIT OR Apache-2.0
-- Normalised schema of a fresh database built by the 30-migration chain that the
-- 0.1.0 baseline replaced; written by `python -m tools.schema_equivalence reference`.

"""
BASELINE_HEADER = """\
-- SPDX-License-Identifier: MIT OR Apache-2.0
-- Generated by `python -m tools.schema_equivalence baseline` from a database built by
-- the 30-migration chain it replaces; tools/schema_equivalence.py proves the result
-- equal to migrations/reference/schema-030.sql. Objects are owned by the migrating
-- role. Alembic owns the transaction; bonafides migrate records the ledger row.
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '60s';
SET LOCAL check_function_bodies = false;
SET LOCAL search_path = '';
"""
BASELINE_ROWS = """\
INSERT INTO bonafides.installation_state(singleton) VALUES(true);
INSERT INTO bonafides.local_model_reservations(singleton) VALUES(true);
-- Quarantine clones need transaction-local tables; the database is the migrator's.
DO $$ BEGIN
 EXECUTE format('GRANT TEMPORARY ON DATABASE %I TO bonafides_runtime',current_database());
END $$;
"""


class EquivalenceError(RuntimeError):
    """The target or dump cannot support a trustworthy comparison."""


def _kept(line: str) -> bool:
    return not (_SESSION.fullmatch(line) or _BANNER.fullmatch(line) or _RESTRICT.fullmatch(line))


def normalise(dump: str) -> str:
    """Return the dump's object entries, each with its header, in a stable order."""
    entries: list[list[str]] = []
    for line in dump.splitlines():
        if line == "--" or not _kept(line):
            continue
        if _HEADER.fullmatch(line):
            entries.append([line])
        elif entries:
            entries[-1].append(line)
        elif line:
            raise EquivalenceError(f"statement before the first object header: {line[:80]}")
    return "\n\n".join(sorted("\n".join(entry).strip("\n") for entry in entries)) + "\n"


def facts(conn: Connection) -> str:
    rows = [
        "-- Fact: runtime database TEMPORARY "
        + str(
            conn.execute(
                text(
                    "SELECT has_database_privilege('bonafides_runtime',current_database(),'TEMPORARY')"
                )
            ).scalar_one()
        ).lower()
    ]
    tables = conn.execute(
        text("""SELECT schemaname||'.'||tablename FROM pg_catalog.pg_tables
        WHERE schemaname = ANY(:schemas) ORDER BY 1"""),
        {"schemas": list(SCHEMAS)},
    ).scalars()
    for table in tables:
        if table in LEDGER_TABLES:
            continue
        schema, name = table.split(".")
        count = conn.execute(
            text(f'SELECT count(*) FROM "{schema}"."{name}"')  # names come from the catalog
        ).scalar_one()
        rows.append(f"-- Fact: {table} rows {count}")
    return "\n".join(rows) + "\n"


def compare(reference: str, actual: str) -> list[str]:
    return list(
        difflib.unified_diff(
            reference.splitlines(), actual.splitlines(), "reference", "migrations", lineterm=""
        )
    )


def baseline(dump: str) -> str:
    """Recreate the dumped ``bonafides`` schema as the migrating role, without ledger rows."""
    lines: list[str] = []
    for line in dump.splitlines():
        if not _kept(line) or line == "--" or _HEADER.fullmatch(line):
            continue
        owner = _OWNER.fullmatch(line)
        if owner:
            if owner.group(2) != MIGRATOR:
                raise EquivalenceError(f"object owned by {owner.group(2)}")
            continue
        for deparsed, original in RESPELLED.items():
            line = line.replace(deparsed, original)
        lines.append(line)
    # Removed frames leave blank runs; the check proves no function body changed.
    body = re.sub(r"\n{3,}", "\n\n", "\n".join(lines).strip("\n"))
    return BASELINE_HEADER + body + "\n\n" + BASELINE_ROWS


def _dump(container: str, database: str, schemas: Sequence[str]) -> str:
    command = ["docker", "exec", container, "pg_dump", "-U", "postgres", "-d", database]
    command += ["--schema-only", "--no-tablespaces", *(f"--schema={name}" for name in schemas)]
    return subprocess.run(command, check=True, capture_output=True, text=True).stdout


def _connection_url(dsn_file: Path) -> str:
    return (
        make_url(read_secret(dsn_file, "migration_dsn"))
        .set(drivername="postgresql+psycopg")
        .render_as_string(hide_password=False)
    )


def _require_empty(url: str) -> None:
    engine = create_engine(url, connect_args={"connect_timeout": 5})
    try:
        with engine.connect() as conn:
            present = conn.execute(
                text("SELECT count(*) FROM pg_catalog.pg_namespace WHERE nspname = ANY(:schemas)"),
                {"schemas": list(SCHEMAS)},
            ).scalar_one()
    finally:
        engine.dispose()
    if present:
        raise EquivalenceError("target database is not empty; use a fresh disposable database")


def _facts(url: str) -> str:
    engine = create_engine(url, connect_args={"connect_timeout": 5})
    try:
        with engine.connect() as conn:
            return facts(conn)
    finally:
        engine.dispose()


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Compare the migrated schema with a reference.")
    parser.add_argument("mode", choices=("check", "reference", "baseline"))
    parser.add_argument("--migration-dsn-file", type=Path, required=True)
    parser.add_argument(
        "--container", required=True, help="PostgreSQL 18 container running pg_dump"
    )
    parser.add_argument("--database", required=True, help="empty database the DSN points at")
    parser.add_argument("--output", type=Path, help="file written by reference and baseline")
    parser.add_argument(
        "--reference", type=Path, default=Path("migrations/reference/schema-030.sql")
    )
    arguments = parser.parse_args(argv)
    if arguments.mode != "check" and arguments.output is None:
        parser.error(f"{arguments.mode} requires --output")
    url = _connection_url(arguments.migration_dsn_file)
    _require_empty(url)
    migrate(MigrationSettings(url))
    if arguments.mode == "baseline":
        arguments.output.write_text(
            baseline(_dump(arguments.container, arguments.database, SCHEMAS[:1]))
        )
        return 0
    dump = _dump(arguments.container, arguments.database, SCHEMAS)
    actual = REFERENCE_HEADER + normalise(dump) + "\n" + _facts(url)
    if arguments.mode == "reference":
        arguments.output.write_text(actual)
        return 0
    difference = compare(arguments.reference.read_text(), actual)
    if difference:
        print("\n".join(difference))
        print(f"Schema differs from {arguments.reference}.", file=sys.stderr)
        return 1
    print(f"Schema equals {arguments.reference} after normalisation.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
