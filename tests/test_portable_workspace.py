SCHEMA = Path(__file__).parents[1] / "docs" / "schemas" / "bonafides-workspace-1.schema.json"
# Published bytes generated by Pydantic 2.12.5. Contract changes need a new version;
# generator-only changes require semantic equivalence review before updating this pin.
PUBLISHED_V1_SHA256 = "29375b648a6fffc31a6494da06ae54685278c2172005a24c91e29d0df9ea96e1"


def _empty(owner: UUID | None = None) -> tuple[Manifest, dict[str, bytes]]:
    manifest = Manifest(
        format="bonafides-workspace",
        format_version=1,
        source_schema_version=WORKSPACE_RECORD_SCHEMA,
        created_at=datetime(2026, 11, 2, tzinfo=UTC),
        source_namespace=uuid4(),
        source_owner_id=owner or uuid4(),
        current_profile_revision_id=uuid4(),
        manifest_sha256="0" * 64,
        records={table: [] for table in COLUMNS},
        blob_manifest=[],
        exclusions=list(EXCLUSIONS),
    )
    return manifest.model_copy(update={"manifest_sha256": manifest_digest(manifest)}), {}


def _wire(data: bytes) -> dict[str, Any]:
    with zipfile.ZipFile(io.BytesIO(data)) as archive:
        return cast(dict[str, Any], json.loads(archive.read("manifest.json")))


def test_committed_schema_is_generated_from_the_models() -> None:
    assert SCHEMA.read_text(encoding="utf-8") == json_schema(), (
        "regenerate with: python -m bonafides.portable_workspace > "
        + str(SCHEMA)
        + "; after a Pydantic upgrade, update the schema and pin only after confirming "
        "semantic equivalence with reviewer sign-off; contract changes need a new format_version"
    )


def test_published_schema_never_changes_under_the_same_version() -> None:
    digest = hashlib.sha256(json_schema().encode()).hexdigest()
    assert digest == PUBLISHED_V1_SHA256, (
        "contract changes need a new format_version; Pydantic generator-only changes "
        "may update the schema and pin only after semantic equivalence review and reviewer sign-off"
    )


def test_sections_carry_exactly_the_reviewed_portable_columns() -> None:
    tables = [table for section in SECTION_TABLES.values() for table in section]
    assert sorted(tables) == sorted(COLUMNS)
    for section, field in WorkspaceSections.model_fields.items():
        model = cast(type[BaseModel], field.annotation)
        for table, rows in model.model_fields.items():
            assert table in SECTION_TABLES[section]
            row = cast(type[BaseModel], cast(Any, rows.annotation).__args__[0])
            if row is ModelRunProvenance:
                row = cast(type[BaseModel], ModelRunProvenance.model_fields["record"].annotation)
            assert tuple(row.model_fields) == COLUMNS[table], table


def test_workspace_wire_has_sections_and_no_database_schema() -> None:
    manifest, blobs = _empty()
    wire = _wire(_encoded(manifest, blobs))
    assert (wire["format"], wire["format_version"]) == ("bonafides-workspace", 1)
    assert "source_schema_version" not in wire and "records" not in wire
    assert set(wire["sections"]) == set(SECTION_TABLES)
    with decode_archive(
        _encoded(manifest, blobs), expected_source_owner=manifest.source_owner_id
    ) as decoded:
        assert decoded.manifest == manifest


@pytest.mark.parametrize(
    "format_name,version",
    [
        ("bonafides-workspace", 2),
        ("bonafides-workspace", 0),
        ("bonafides-workspace", "1"),
        ("bonafides-workspace", True),
        ("bonafides-portable", 3),
        ("another-format", 1),
        (None, 1),
    ],
)
def test_unsupported_format_or_version_is_refused(format_name: object, version: object) -> None:
    manifest, blobs = _empty()
    data = _encoded(manifest, blobs)
    wire = _wire(data)
    wire.update(format=format_name, format_version=version)
    with pytest.raises(ArchiveError, match="incompatible_portable_format"):
        decode_archive(
            repack(data, manifest=canonical_json(wire).encode()),
            expected_source_owner=manifest.source_owner_id,
        )


@pytest.mark.parametrize(
    "column,value",
    [
        ("unknown", "forbidden"),
        ("version", "1"),
        ("created_at", "2026-11-02 10:00:00"),
        ("current_revision_id", "not-a-uuid"),
    ],
)
def test_contract_refuses_rows_outside_their_typed_shape(column: str, value: object) -> None:
    manifest, blobs = _empty()
    row = {
        "owner_id": str(manifest.source_owner_id),
        "id": str(uuid4()),
        "version": 1,
        "current_revision_id": str(manifest.current_profile_revision_id),
        "created_at": "2026-11-02T10:00:00.123456+00:00",
        column: value,
    }
    wire = _wire(_encoded(manifest, blobs))
    wire["sections"]["profile"]["profiles"] = [row]
    wire["manifest_sha256"] = hashlib.sha256(
        canonical_json({k: v for k, v in wire.items() if k != "manifest_sha256"}).encode()
    ).hexdigest()
    with pytest.raises(ArchiveError, match="invalid_portable_manifest"):
        decode_archive(
            repack(_encoded(manifest, blobs), manifest=canonical_json(wire).encode()),
            expected_source_owner=manifest.source_owner_id,
        )
    legacy_shape = manifest.model_copy(update={"source_schema_version": 29})
    with pytest.raises(ArchiveError, match="incompatible_portable_format"):
        _encoded(legacy_shape, blobs)


def _import(
    context: SourceContext,
    parser: ImportParserClient,
    renderer_spool: Path,
    payload: bytes,
) -> dict[str, object]:
    checkpoint_id, runtime_pins = _checkpoint(context, parser.spool, renderer_spool)
    prepared: Prepared = _approved_import(context, payload)
    with context.runtime.transaction() as conn:
        task = claim_control(conn, uuid4())
        assert task is not None and task.id == prepared.workflow_id
        consume_action_approval(
            conn,
            task,
            action_kind="replace_workspace",
            destination=prepared.destination,
            payload=prepared.payload,
            target_version=cast(int, prepared.approval["target_version"]),
        )
        control = begin_control(conn, task)
    maintenance = InstallationMaintenance(context.runtime, control, parser.spool, renderer_spool)
    with maintenance.quiescent():
        result = import_controlled_owner_data(
            context.runtime,
            context.identity.settings,
            control,
            payload,
            expected_source_owner=context.owner_id,
            checkpoint_id=checkpoint_id,
            runtime_pins=runtime_pins,
        )
        maintenance.finish(result)
    return result


def _usage(context: SourceContext, archive: PortableArchive) -> dict[str, object]:
    with context.runtime.transaction() as conn:
        return {
            **{
                str(row["id"]): claim_usage.claim_usage(
                    conn, context.owner_id, UUID(str(row["id"])), history=True
                )
                for row in archive.manifest.records["professional_claims"]
            },
            **{
                str(row["id"]): claim_usage.application_claims(
                    conn, context.owner_id, UUID(str(row["id"]))
                )
                for row in archive.manifest.records["applications"]
            },
        }


@pytest.mark.postgres
def test_workspace_export_reimports_claims_usage_documents_and_tracking(
    catalog: SourceContext,
    parser: ImportParserClient,
    renderer_spool: Path,
    monkeypatch: pytest.MonkeyPatch,
    tmp_path: Path,
) -> None:
    _, application = _pair(catalog, monkeypatch, tmp_path, "valid")
    # Usage now pins a superseded revision of an archived claim on reclassified evidence.
    assert _reclassify(catalog).status_code == 200
    assert _edit_claim(catalog).status_code == 200
    assert _archive_claim(catalog).status_code == 200
    application = _stage(catalog, _get(catalog, application), "applied")
    application = _write(catalog, application, "notes", {"body": "Synthetic portable note"})
    application = _write(
        catalog,
        application,
        "contacts",
        {"display_name": "Fictional recruiter", "email": None, "role_label": None},
    )
    _write(catalog, application, "appointments", _appointment())
    output = io.BytesIO()
    export_owner_data(catalog.runtime, catalog.identity.settings, catalog.owner_id, output)
    payload = output.getvalue()
    with zipfile.ZipFile(io.BytesIO(payload)) as written:
        WorkspaceManifest.model_validate_json(written.read("manifest.json"), strict=True)
    original = decode_archive(payload, expected_source_owner=catalog.owner_id)
    records = original.manifest.records
    links = records["document_claim_links"]
    assert links and all(row["claim_revision_id"] for row in links)
    assert records["application_notes"] and records["appointments"]
    assert len(records["evidence_classification_changes"]) > len(records["evidence_records"])
    before = _usage(catalog, original)
    assert any(
        item["superseded"] and item["archived"]
        for usage in before.values()
        for item in cast(list[dict[str, Any]], cast(dict[str, Any], usage)["items"])
    )

    _import(catalog, parser, renderer_spool, payload)

    with (
        catalog.runtime.engine.connect().execution_options(
            isolation_level="REPEATABLE READ"
        ) as conn,
        conn.begin(),
    ):
        restored = collect_owner_data(conn, catalog.identity.settings, catalog.owner_id)
    for section in ("profile", "claims", "evidence", "claim_usage", "documents", "tracking"):
        for family in SECTION_TABLES[section]:
            assert restored.manifest.records[family] == records[family], family
    assert _usage(catalog, restored) == before


@pytest.mark.postgres
def test_unsupported_version_is_refused_before_any_row_or_blob_write(
    catalog: SourceContext, parser: ImportParserClient, renderer_spool: Path
) -> None:
    payload = b"Synthetic staged bytes that must never be written.\n"
    digest = hashlib.sha256(payload).hexdigest()
    manifest, blobs = _empty(catalog.owner_id)
    archive = PortableArchive(manifest, blobs)
    wire = _wire(_encoded(archive.manifest, archive.blobs))
    wire["format_version"] = 2
    wire["blob_manifest"] = [
        {
            "blob_id": str(uuid4()),
            "sha256": digest,
            "byte_length": len(payload),
            "media_type": "text/plain",
            "archive_member": f"blobs/{digest}",
        }
    ]
    target = io.BytesIO()
    with zipfile.ZipFile(target, "w", compression=zipfile.ZIP_STORED) as written:
        written.writestr("manifest.json", canonical_json(wire))
        written.writestr(f"blobs/{digest}", payload)
    owner_root = catalog.identity.settings.blob_root / str(catalog.owner_id)

    def state() -> tuple[object, ...]:
        with catalog.identity.admin.transaction() as conn:
            rows = conn.execute(
                text("""SELECT (SELECT count(*) FROM bonafides.portable_staged_files),
                (SELECT count(*) FROM bonafides.blobs),
                (SELECT count(*) FROM bonafides.profile_revisions),
                (SELECT count(*) FROM bonafides.sessions)""")
            ).one()
        files = sorted(str(path) for path in owner_root.rglob("*")) if owner_root.exists() else []
        return (*rows, files)

    before = state()
    with pytest.raises(ArchiveError, match="incompatible_portable_format"):
        _import(catalog, parser, renderer_spool, target.getvalue())
    assert state() == before


@pytest.mark.postgres
@pytest.mark.parametrize("version", [1, 2])
@pytest.mark.parametrize(
    "timestamp",
    [None, "2026-11-02T10:00:00Z", "2026-11-02 10:00:00+00", "2026-11-02T10:00:00.1234567Z"],
)
def test_legacy_portable_archive_still_imports(
    catalog: SourceContext,
    parser: ImportParserClient,
    renderer_spool: Path,
    monkeypatch: pytest.MonkeyPatch,
    tmp_path: Path,
    version: int,
    timestamp: str | None,
) -> None:
    _pair(catalog, monkeypatch, tmp_path, "valid")
    output = io.BytesIO()
    export_owner_data(catalog.runtime, catalog.identity.settings, catalog.owner_id, output)
    exported = decode_archive(output, expected_source_owner=catalog.owner_id)
    legacy = exported.manifest.model_copy(
        update={"format": "bonafides-portable", "format_version": version}
    )
    if timestamp is not None:
        provenance = legacy.records["model_run_provenance"]
        assert provenance
        for item in provenance:
            record = cast(dict[str, Any], item["record"])
            record["created_at"] = timestamp
            if record["finished_at"] is not None:
                record["finished_at"] = timestamp
    legacy = legacy.model_copy(update={"manifest_sha256": manifest_digest(legacy)})
    payload = _encoded(legacy, exported.blobs)
    assert _wire(payload)["records"] == legacy.records

    _import(catalog, parser, renderer_spool, payload)

    with (
        catalog.runtime.engine.connect().execution_options(
            isolation_level="REPEATABLE READ"
        ) as conn,
        conn.begin(),
    ):
        restored = collect_owner_data(conn, catalog.identity.settings, catalog.owner_id)
    for table in ("professional_claims", "claim_revisions", "document_claim_links"):
        assert restored.manifest.records[table] == legacy.records[table], table
    output = io.BytesIO()
    export_owner_data(catalog.runtime, catalog.identity.settings, catalog.owner_id, output)
    wire = _wire(output.getvalue())
    WorkspaceManifest.model_validate_json(canonical_json(wire), strict=True)
    for item in restored.manifest.records["model_run_provenance"]:
        record = cast(dict[str, Any], item["record"])
        with catalog.runtime.transaction() as conn:
            stored = conn.execute(
                text("""SELECT record_sha256 FROM bonafides.portable_model_history
                WHERE owner_id=:owner AND id=:id"""),
                {"owner": catalog.owner_id, "id": record["id"]},
            ).scalar_one()
        assert stored == hashlib.sha256(canonical_json(record).encode()).hexdigest()
