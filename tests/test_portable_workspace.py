def _empty(owner: UUID | None = None) -> tuple[Manifest, dict[str, bytes]]:
    manifest = Manifest(
        format="bonafides-workspace",
        format_version=1,
        source_schema_version=WORKSPACE_RECORD_SCHEMA,
        created_at=datetime(2026, 11, 2, tzinfo=UTC),
        source_namespace=uuid4(),
        source_owner_id=owner or uuid4(),
        current_profile_revision_id=uuid4(),
        manifest_sha256="0" * 64,
        records={table: [] for table in COLUMNS if table != "document_conversation_turns"},
        blob_manifest=[],
        exclusions=list(EXCLUSIONS),
    )
    return manifest.model_copy(update={"manifest_sha256": manifest_digest(manifest)}), {}


def _wire(data: bytes) -> dict[str, Any]:
    with zipfile.ZipFile(io.BytesIO(data)) as archive:
        return cast(dict[str, Any], json.loads(archive.read("manifest.json")))


